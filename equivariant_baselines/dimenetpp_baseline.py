# Convert structures → PyG graphs
# We precompute everything DimeNet++ needs:
#   - edge_index, dist (for radial basis)
#   - triplet indices + angles (for spherical basis)
# This avoids all internal DimeNet++ graph building issues with PBC.

def struct_to_graph(struc, target, cutoff=CUTOFF, max_nbr=MAX_NEIGHBORS):
    s = struc
    z = torch.tensor([site.specie.Z for site in s], dtype=torch.long)
    pos = torch.tensor(s.cart_coords, dtype=torch.float32)

    src, dst, vecs, dists = [], [], [], []
    all_nbrs = s.get_all_neighbors(cutoff, include_index=True)
    for i, nbrs in enumerate(all_nbrs):
        nbrs = sorted(nbrs, key=lambda x: x[1])[:max_nbr]
        for site, d, j, _ in nbrs:
            src.append(i); dst.append(j)
            vecs.append(site.coords - s[i].coords)
            dists.append(d)

    ei = torch.tensor([src, dst], dtype=torch.long)
    ev = torch.tensor(np.array(vecs), dtype=torch.float32)
    ed = torch.tensor(dists, dtype=torch.float32)

    # --- Precompute triplets + angles (biggest speed gain) ---
    E = ei.size(1)
    N = z.size(0)
    dst_t = ei[1]
    src_t = ei[0]

    degree = torch.zeros(N, dtype=torch.long)
    degree.scatter_add_(0, dst_t, torch.ones(E, dtype=torch.long))
    max_deg = degree.max().item()

    trip_src = torch.zeros(0, dtype=torch.long)
    trip_dst = torch.zeros(0, dtype=torch.long)
    trip_angle = torch.zeros(0, dtype=torch.float32)
    trip_dist = torch.zeros(0, dtype=torch.float32)

    if max_deg >= 2:
        sort_idx = torch.argsort(dst_t)
        ptr = torch.zeros(N + 1, dtype=torch.long)
        ptr[1:] = degree.cumsum(0)

        ts_list, td_list = [], []
        for d in range(2, max_deg + 1):
            nodes_d = (degree == d).nonzero(as_tuple=False).squeeze(-1)
            if nodes_d.size(0) == 0:
                continue
            starts = ptr[nodes_d]
            offs = torch.arange(d).unsqueeze(0)
            eids = sort_idx[starts.unsqueeze(1) + offs]

            row_idx = torch.arange(d).unsqueeze(1).expand(d, d-1)
            col_list = []
            for r in range(d):
                col_list.append(torch.cat([torch.arange(r), torch.arange(r+1, d)]))
            col_idx = torch.stack(col_list)

            ts_list.append(eids[:, row_idx.reshape(-1)].reshape(-1))
            td_list.append(eids[:, col_idx.reshape(-1)].reshape(-1))

        if ts_list:
            trip_src = torch.cat(ts_list)
            trip_dst = torch.cat(td_list)

            va = -ev[trip_src]
            vb = -ev[trip_dst]
            cos_a = (va * vb).sum(-1) / (va.norm(dim=-1) * vb.norm(dim=-1) + 1e-8)
            trip_angle = torch.acos(cos_a.clamp(-1+1e-7, 1-1e-7))
            trip_dist = ed[trip_src]

    return Data(
        z=z, pos=pos,
        edge_index=ei, edge_vec=ev, edge_dist=ed,
        trip_src=trip_src, trip_dst=trip_dst,
        trip_angle=trip_angle, trip_dist=trip_dist,
        y=torch.tensor(target, dtype=torch.float32),
    )

