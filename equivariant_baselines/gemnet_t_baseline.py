# Convert structures → PyG graphs

def struct_to_graph(struc, target, cutoff=CUTOFF, max_nbr=MAX_NEIGHBORS):
    # 1. Basic Atomic Data
    z = torch.tensor([site.specie.Z for site in struc], dtype=torch.long)
    pos = torch.tensor(struc.cart_coords, dtype=torch.float32)

    # 2. Vectorized Neighbor Search (Replaces pymatgen loops)
    # This creates edge_index [2, E]
    edge_index = radius_graph(pos, r=cutoff, loop=False, max_num_neighbors=max_nbr)

    # 3. Calculate Edge Vectors and Distances
    j, i = edge_index # target, source
    edge_vec = pos[j] - pos[i]
    edge_dist = edge_vec.norm(dim=-1)

    return Data(
        z=z, pos=pos,
        edge_index=edge_index,
        edge_attr=edge_vec,
        edge_dist=edge_dist,
        y=torch.tensor(target, dtype=torch.float32)
    )

