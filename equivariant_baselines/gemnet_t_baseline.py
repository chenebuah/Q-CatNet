# Model — Streamlined GemNet-T

class RadialBasis(nn.Module):
    def __init__(self, K=NUM_RADIAL, cut=CUTOFF):
        super().__init__()
        self.cut = cut
        self.register_buffer("freq", torch.arange(1, K+1).float() * np.pi / cut)

    def forward(self, d):
        d = d.unsqueeze(-1)
        rbf = (2/self.cut)**0.5 * torch.sin(self.freq * d) / (d + 1e-8)
        x = d / self.cut
        env = (1 - 10*x**3 + 15*x**4 - 6*x**5) * (d < self.cut).float()
        return rbf * env

class InteractionBlock(nn.Module):
    def __init__(self, D, Dt, K, Kc):
        super().__init__()
        self.rbf_proj  = nn.Linear(K, D, bias=False)
        self.trip_proj = nn.Sequential(nn.Linear(D, Dt), nn.SiLU(), nn.Linear(Dt, Dt))
        self.trip_cbf = nn.Linear(Kc, Dt, bias=False)
        self.msg = nn.Sequential(nn.Linear(Dt, D), nn.SiLU(), nn.Linear(D, D))
        self.update = nn.Sequential(nn.Linear(D, D), nn.SiLU(), nn.Linear(D, D))
        self.atom_out = nn.Sequential(nn.Linear(D, D), nn.SiLU(), nn.Linear(D, D))

    def forward(self, h, m, rbf, cbf, edge_index, tri_idx):
        m_g = m * self.rbf_proj(rbf)
        t = self.trip_proj(m_g)

        # Vectorized Triplet Aggregation
        t_agg = torch.zeros_like(t)
        if tri_idx is not None:
            # tri_idx[1] = incoming edge, tri_idx[2] = outgoing edge
            t_msg = t[tri_idx[1]] * self.trip_cbf(cbf)
            t_agg.index_add_(0, tri_idx[2], t_msg)

        m = self.update(m_g + self.msg(t_agg))
        a_msg = self.atom_out(m)

        # Vectorized Atom Aggregation
        h_agg = torch.zeros_like(h)
        h_agg.index_add_(0, edge_index[1], a_msg)
        return h + h_agg, m

class GemNetT(nn.Module):
    def __init__(self, D=EMB_DIM, Dt=TRIP_DIM, K=NUM_RADIAL, S=NUM_SPHERICAL, n_blocks=NUM_BLOCKS):
        super().__init__()
        self.S = S
        self.rbf = RadialBasis(K)
        self.atom_emb = nn.Embedding(119, D)
        self.edge_init = nn.Sequential(nn.Linear(2*D + K, D), nn.SiLU(), nn.Linear(D, D))
        self.blocks = nn.ModuleList([InteractionBlock(D, Dt, K, K*S) for _ in range(n_blocks)])
        self.heads = nn.ModuleList([nn.Sequential(nn.Linear(D, D), nn.SiLU(), nn.Linear(D, 1)) for _ in range(n_blocks+1)])

    def get_triplets(self, edge_index, num_nodes):
        row, col = edge_index # i->j
        # Find edges where destination of edge1 == source of edge2
        # Use a vectorized approach to find triplets (i->j->k)
        # For simplicity in this demo, we use a torch-based connection map
        deg = torch.zeros(num_nodes, dtype=torch.long, device=edge_index.device)
        deg.index_add_(0, row, torch.ones_like(row))

        # Find which edges share a node
        # This is a high-level vectorized trick:
        edge_to_node_map = col
        node_to_edge_map = row

        # Creating triplet indices (e_in, e_out)
        # For brevity, this is the logic that replaces the for-loop
        # In a production environment, one might use torch_runstats or specialized kernels
        # Here we use a logical mask approach:
        e_in, e_out = torch.where(col.unsqueeze(1) == row.unsqueeze(0))
        # Filter out self-backtracking (i->j->i)
        mask = row[e_in] != col[e_out]
        return torch.stack([e_in[mask], e_out[mask]])

    def forward(self, data):
        z, ei, ev, ed = data.z, data.edge_index, data.edge_attr, data.edge_dist
        batch = data.batch

        # 1. Vectorized Triplet & Angle Calculation
        # We calculate this once per forward pass
        tri_idx = self.get_triplets(ei, z.size(0))

        # Angles: cos(theta) = (v_ij . v_jk) / (|v_ij||v_jk|)
        v_ij = -ev[tri_idx[0]] # vector j->i
        v_jk = ev[tri_idx[1]]  # vector j->k
        cos = (v_ij * v_jk).sum(-1) / (v_ij.norm(dim=-1) * v_jk.norm(dim=-1) + 1e-8)
        angles = torch.acos(cos.clamp(-1+1e-7, 1-1e-7))

        # 2. Vectorized CBF
        rbf_tri = self.rbf(ed[tri_idx[0]])
        n_range = torch.arange(self.S, device=z.device).view(1, -1)
        cbf_angle = torch.cos(n_range * angles.unsqueeze(-1))
        cbf = (rbf_tri.unsqueeze(-1) * cbf_angle.unsqueeze(-2)).view(tri_idx.size(1), -1)

        # 3. Main Message Passing
        h = self.atom_emb(z)
        rbf_edges = self.rbf(ed)
        m = self.edge_init(torch.cat([h[ei[0]], h[ei[1]], rbf_edges], -1))

        out = self.heads[0](h)
        for i, blk in enumerate(self.blocks):
            h, m = blk(h, m, rbf_edges, cbf, ei, torch.cat([torch.zeros((1, tri_idx.size(1)), device=z.device), tri_idx], 0).long())
            out = out + self.heads[i+1](h)

        # Global Pooling
        return torch.zeros(batch.max()+1, 1, device=z.device).index_add_(0, batch, out).squeeze(-1)

