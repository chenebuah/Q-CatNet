# --- Symmetric contraction (many-body correlation) ---
class SymmetricContraction(nn.Module):
    """
    Core MACE operation: builds many-body features via repeated tensor
    products of the atomic basis A_i with itself, then contracts to
    output irreps using learnable weights.

    For correlation=2 (3-body):  B_i = contract(A_i ⊗ A_i)
    For correlation=3 (4-body):  B_i = contract(A_i ⊗ A_i ⊗ A_i)

    This is what makes MACE special — it captures higher body-order
    interactions without explicitly enumerating triplets/quadruplets.
    """
    def __init__(self, irreps_in, irreps_out, correlation, num_elements=119):
        super().__init__()
        self.correlation = correlation
        self.irreps_in = irreps_in
        self.irreps_out = irreps_out
        self.num_elements = num_elements

        # For each correlation order, we do a tensor product of accumulated
        # features with the original A, then project to output irreps.
        # Simplified: we use a sequence of TP + linear contractions.
        self.tp_layers = nn.ModuleList()
        self.linear_layers = nn.ModuleList()

        current_irreps = irreps_in
        for _ in range(correlation):
            tp = FullyConnectedTensorProduct(
                current_irreps, irreps_in, irreps_out, shared_weights=True
            )
            self.tp_layers.append(tp)
            lin = E3Linear(irreps_out, irreps_out)
            self.linear_layers.append(lin)
            current_irreps = irreps_out

        # Element-dependent weights (MACE uses per-element contractions)
        self.element_proj = nn.Linear(num_elements, irreps_out.dim, bias=False)

    def forward(self, A, z):
        """
        A: [N, irreps_in.dim] atomic basis (sum of neighbor messages)
        z: [N] atomic numbers
        Returns: [N, irreps_out.dim] many-body features
        """
        # Accumulate correlations: start with A, repeatedly TP with A
        current = A
        for tp, lin in zip(self.tp_layers, self.linear_layers):
            current = tp(current, A)
            current = lin(current)

        # Element-dependent weighting
        z_onehot = F.one_hot(z.clamp(0, self.num_elements - 1),
                             self.num_elements).float()
        elem_w = self.element_proj(z_onehot)  # [N, D]
        return current * elem_w


# --- MACE interaction block ---
class MACEInteraction(nn.Module):
    """
    Single MACE layer:
      1. Message passing: TP(h_j, Y_ij) weighted by radial MLP → aggregate to A_i
      2. Symmetric contraction: A_i^(correlation) → many-body features B_i
      3. Linear readout + skip connection
    """
    def __init__(self, irreps_in, irreps_hidden, irreps_sh, num_radial, correlation):
        super().__init__()
        # Message: node features ⊗ edge SH, weighted by radial network
        self.message_tp = FullyConnectedTensorProduct(
            irreps_in, irreps_sh, irreps_hidden, shared_weights=False
        )
        self.radial_mlp = nn.Sequential(
            nn.Linear(num_radial, 64), nn.SiLU(),
            nn.Linear(64, self.message_tp.weight_numel)
        )

        # Symmetric contraction for many-body features
        self.contraction = SymmetricContraction(
            irreps_hidden, irreps_hidden, correlation
        )

        # Output linear + skip
        self.linear_out = E3Linear(irreps_hidden, irreps_hidden)
        self.skip = E3Linear(irreps_in, irreps_hidden) if irreps_in != irreps_hidden else nn.Identity()
        self.norm = nn.LayerNorm(irreps_hidden.dim)

    def forward(self, h, z, edge_index, edge_sh, rbf):
        src, dst = edge_index
        N = h.size(0)

        # --- Message passing ---
        tp_w = self.radial_mlp(rbf)                        # [E, weight_numel]
        msg = self.message_tp(h[src], edge_sh, tp_w)       # [E, D_hidden]

        # Aggregate: A_i = sum_j msg_ij
        A = torch.zeros(N, msg.size(-1), device=h.device, dtype=msg.dtype)
        A.scatter_add_(0, dst.unsqueeze(-1).expand_as(msg), msg)

        # --- Symmetric contraction (many-body) ---
        B = self.contraction(A, z)                          # [N, D_hidden]

        # --- Output ---
        out = self.linear_out(B)
        out = self.norm(self.skip(h) + out)
        return out


# --- Full MACE model ---
class MACE(nn.Module):
    def __init__(self):
        super().__init__()
        # Atom embedding → full irreps dim (higher-l channels start as 0)
        self.atom_emb = nn.Embedding(119, FULL_DIM, padding_idx=0)

        # Initial linear to hidden irreps (ensures correct irrep structure)
        self.input_proj = E3Linear(HIDDEN_IRREPS, HIDDEN_IRREPS)

        # Interaction blocks
        self.interactions = nn.ModuleList([
            MACEInteraction(
                irreps_in=HIDDEN_IRREPS,
                irreps_hidden=HIDDEN_IRREPS,
                irreps_sh=SH_IRREPS,
                num_radial=NUM_RADIAL,
                correlation=CORRELATION,
            )
            for _ in range(NUM_INTERACTIONS)
        ])

        # Per-block readout heads (MACE sums contributions from each layer)
        self.readouts = nn.ModuleList([
            nn.Sequential(
                E3Linear(HIDDEN_IRREPS, Irreps("1x0e")),
                nn.SiLU(),
                nn.Linear(1, 64),
                nn.SiLU(),
                nn.Linear(64, 1),
            )
            for _ in range(NUM_INTERACTIONS)
        ])

        # Initial readout
        self.readout_0 = nn.Sequential(
            E3Linear(HIDDEN_IRREPS, Irreps("1x0e")),
            nn.SiLU(),
            nn.Linear(1, 1),
        )

    def forward(self, data):
        z = data.z
        ei = data.edge_index
        edge_sh = data.edge_sh
        rbf = data.rbf
        batch = data.batch if hasattr(data, 'batch') else torch.zeros(z.size(0), dtype=torch.long, device=z.device)

        # Node features
        h = self.input_proj(self.atom_emb(z))

        # Initial contribution
        node_out = self.readout_0(h)  # [N, 1]

        # Interaction layers with per-layer readout
        for interaction, readout in zip(self.interactions, self.readouts):
            h = interaction(h, z, ei, edge_sh, rbf)
            node_out = node_out + readout(h)  # [N, 1]

        # Sum pooling per graph
        g_out = torch.zeros(batch.max()+1, 1, device=node_out.device, dtype=node_out.dtype)
        g_out.scatter_add_(0, batch.unsqueeze(-1), node_out)
        return g_out.squeeze(-1)


