def bessel_basis(d, K, cutoff):
    """Bessel radial basis functions with polynomial envelope."""
    d = d.unsqueeze(-1)
    n = torch.arange(1, K+1, device=d.device, dtype=d.dtype)
    rbf = (2.0 / cutoff)**0.5 * torch.sin(n * np.pi * d / cutoff) / (d + 1e-8)
    # polynomial envelope p=5
    x = d / cutoff
    env = 1 - 10*x**3 + 15*x**4 - 6*x**5
    env *= (d < cutoff).float()
    return rbf * env

def struct_to_graph(struc, target, cutoff=CUTOFF, max_nbr=MAX_NEIGHBORS):
    s = struc
    z = torch.tensor([site.specie.Z for site in s], dtype=torch.long)
    pos = torch.tensor(s.cart_coords, dtype=torch.float32)

    src, dst, vecs, dists = [], [], [], []
    all_nbrs = s.get_all_neighbors(cutoff, include_index=True)
    for i, nbrs in enumerate(all_nbrs):
        nbrs = sorted(nbrs, key=lambda x: x[1])[:max_nbr]
        for site, d, j, _ in nbrs:
            src.append(i); dst.append(j)
            vecs.append(site.coords - s[i].coords)
            dists.append(d)

    ev = torch.tensor(np.array(vecs), dtype=torch.float32)
    ed = torch.tensor(dists, dtype=torch.float32)

    # Precompute
    edge_dir = ev / (ed.unsqueeze(-1) + 1e-8)
    edge_sh = spherical_harmonics(SH_IRREPS, edge_dir, normalize=True, normalization='component')
    rbf = bessel_basis(ed, NUM_RADIAL, cutoff)

    return Data(
        z=z, pos=pos,
        edge_index=torch.tensor([src, dst], dtype=torch.long),
        edge_sh=edge_sh,
        rbf=rbf,
        y=torch.tensor([target], dtype=torch.float32),
    )

