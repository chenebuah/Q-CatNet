# --- Radial basis + smooth cutoff envelope ---
class RadialBasis(nn.Module):
    def __init__(self, K=NUM_RADIAL, cut=CUTOFF):
        super().__init__()
        self.cut = cut
        self.K = K

    def forward(self, d):
        # Gaussian RBF
        d = d.unsqueeze(-1)
        centers = torch.linspace(0, self.cut, self.K, device=d.device)
        width = (self.cut / self.K) * 0.5
        rbf = torch.exp(-0.5 * ((d - centers) / width) ** 2)
        # smooth cutoff
        x = d / self.cut
        env = 1 - 10*x**3 + 15*x**4 - 6*x**5
        env *= (d < self.cut).float()
        return rbf * env

# --- Equivariant attention block (core of EquiformerV2) ---
class EquivariantAttentionBlock(nn.Module):
    """
    SO(3) equivariant attention:
      1. Project node features → queries/keys/values via e3nn Linear
      2. Compute scalar attention weights from (q·k) + radial MLP
      3. Weighted aggregation of equivariant values
      4. Gate activation + skip connection
    """
    def __init__(self, irreps_in, irreps_sh, num_heads, num_radial):
        super().__init__()
        self.irreps_in = irreps_in
        self.num_heads = num_heads
        self.dim_per_head = irreps_in.dim // num_heads

        # Q, K, V projections (equivariant linear)
        self.proj_q = E3Linear(irreps_in, irreps_in)
        self.proj_k = E3Linear(irreps_in, irreps_in)
        self.proj_v = E3Linear(irreps_in, irreps_in)

        # Tensor product: node features x edge spherical harmonics → messages
        self.tp = o3.FullyConnectedTensorProduct(
            irreps_in, irreps_sh, irreps_in, shared_weights=False
        )
        self.radial_mlp = nn.Sequential(
            nn.Linear(num_radial, 64), nn.SiLU(),
            nn.Linear(64, self.tp.weight_numel)
        )

        # Attention score from radial info
        self.attn_radial = nn.Sequential(
            nn.Linear(num_radial, 64), nn.SiLU(),
            nn.Linear(64, num_heads)
        )

        # Output projection + layer norm
        self.proj_out = E3Linear(irreps_in, irreps_in)

        # Scalar gate for activation
        n_scalars = irreps_in[0].mul  # number of l=0 features
        n_nonscalars = sum(mul for mul, ir in irreps_in if ir.l > 0)
        gate_irreps = Irreps(f"{n_scalars + n_nonscalars}x0e") + Irreps("+".join(
            [f"{mul}x{ir}" for mul, ir in irreps_in if ir.l > 0]
        ))
        self.gate_proj = E3Linear(irreps_in, gate_irreps)
        self.gate = Gate(
            f"{n_scalars}x0e", [torch.sigmoid],
            f"{n_nonscalars}x0e", [torch.sigmoid],
            Irreps("+".join([f"{mul}x{ir}" for mul, ir in irreps_in if ir.l > 0]))
        )

        # Layer norm (scalar part only for stability)
        self.norm = nn.LayerNorm(irreps_in.dim)

    def forward(self, h, edge_index, edge_sh, rbf):
        """
        h:          [N, D] node features (flattened irreps)
        edge_index: [2, E]
        edge_sh:    [E, sh_dim] spherical harmonics of edge vectors
        rbf:        [E, K] radial basis
        """
        src, dst = edge_index
        N = h.size(0)

        q = self.proj_q(h)  # [N, D]
        k = self.proj_k(h)  # [N, D]
        v = self.proj_v(h)  # [N, D]

        # Tensor product: v_j ⊗ Y(r_ij), weighted by radial MLP
        tp_weights = self.radial_mlp(rbf)  # [E, tp_weight_numel]
        msg = self.tp(v[src], edge_sh, tp_weights)  # [E, D]

        # Attention scores: dot product of scalar parts + radial bias
        # Use only l=0 (scalar) part for attention logits
        n_scalar = self.irreps_in[0].mul
        q_scalar = q[dst, :n_scalar]  # [E, n_scalar]
        k_scalar = k[src, :n_scalar]  # [E, n_scalar]

        # Reshape for multi-head: [E, num_heads, head_dim]
        head_dim = n_scalar // self.num_heads
        q_h = q_scalar.view(-1, self.num_heads, head_dim)
        k_h = k_scalar.view(-1, self.num_heads, head_dim)

        # Scaled dot-product attention + radial bias
        attn = (q_h * k_h).sum(-1) / (head_dim ** 0.5)  # [E, num_heads]
        attn = attn + self.attn_radial(rbf)               # [E, num_heads]

        # Softmax per destination node
        attn_max = torch.zeros(N, self.num_heads, device=h.device)
        attn_max.scatter_reduce_(0, dst.unsqueeze(-1).expand_as(attn), attn, reduce="amax")
        attn = torch.exp(attn - attn_max[dst])
        attn_sum = torch.zeros(N, self.num_heads, device=h.device)
        attn_sum.scatter_add_(0, dst.unsqueeze(-1).expand_as(attn), attn)
        attn = attn / (attn_sum[dst] + 1e-8)  # [E, num_heads]

        # Average attention over heads → single scalar per edge
        attn_avg = attn.mean(dim=-1, keepdim=True)  # [E, 1]

        # Weighted message aggregation
        msg_weighted = msg * attn_avg  # [E, D]
        agg = torch.zeros(N, msg.size(-1), device=h.device)
        agg.scatter_add_(0, dst.unsqueeze(-1).expand_as(msg_weighted), msg_weighted)

        # Output projection + gated activation
        out = self.proj_out(agg)
        out = self.gate(self.gate_proj(out))

        # Skip connection + layer norm
        out = self.norm(h + out)
        return out


# --- Full EquiformerV2 model ---
class EquiformerV2(nn.Module):
    def __init__(self):
        super().__init__()
        D = HIDDEN_IRREPS.dim

        # Atom embedding: Z → scalar features, padded to full irreps dim
        self.atom_emb = nn.Embedding(119, D, padding_idx=0)
        self.radial_basis = RadialBasis()

        # Equivariant attention blocks
        self.blocks = nn.ModuleList([
            EquivariantAttentionBlock(HIDDEN_IRREPS, SH_IRREPS, NUM_HEADS, NUM_RADIAL)
            for _ in range(NUM_BLOCKS)
        ])

        # Output: project to scalar → pool → predict
        self.out_proj = E3Linear(HIDDEN_IRREPS, Irreps("1x0e"))
        self.out_mlp = nn.Sequential(
            nn.Linear(1, 64), nn.SiLU(),
            nn.Linear(64, 1)
        )

    def forward(self, data):
        z = data.z
        ei = data.edge_index
        ev = data.edge_vec
        ed = data.edge_dist
        batch = data.batch if hasattr(data, 'batch') else torch.zeros(z.size(0), dtype=torch.long, device=z.device)

        # Spherical harmonics of edge directions
        edge_dir = ev / (ed.unsqueeze(-1) + 1e-8)  # unit vectors
        edge_sh = spherical_harmonics(SH_IRREPS, edge_dir, normalize=True, normalization='component')

        # Radial basis
        rbf = self.radial_basis(ed)

        # Node features: atom embedding (fills full irreps dim, higher-l start as 0)
        h = self.atom_emb(z)  # [N, D]

        # Equivariant attention blocks
        for block in self.blocks:
            h = block(h, ei, edge_sh, rbf)

        # Pool to graph level: take scalar part → MLP
        scalar = self.out_proj(h)  # [N, 1]
        pred = self.out_mlp(scalar)  # [N, 1]

        # Sum pooling per graph
        g_out = torch.zeros(batch.max()+1, 1, device=pred.device)
        g_out.scatter_add_(0, batch.unsqueeze(-1), pred)
        return g_out.squeeze(-1)


